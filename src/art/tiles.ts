// The terrain's grids and palettes: grass, water, trees, paths, the shore and
// road transitions, tall grass, soil, the house footprint and the volcano's
// floor. tilesets.ts bakes them into the tilesets and their skins.
//
// Every grid here is 32 cells, drawn as it stands at ART_PX (2px), the cell
// the field's sprites have: a tile is still 64px. They were 16-cell grids on
// 4px cells, the floors kept blocky (keepBlocky) and the rest put through
// Scale2x, so the ground the 2px hero walked on was the coarsest thing on the
// screen. Each floor keeps its 16-cell layout -- the lattice, its spacing, its
// share of marked cells and its two tones -- with every 4px mark redrawn as a
// 2px shape of the same four cells; the trees and the boulder are their
// Scale2x bake with the outline thinned to one cell and the canopy's tone
// bands broken into leaves; the transitions are generated (see SHORE_PALETTE).

// Terrain is a regular diagonal pattern, two tones, deliberately low contrast.
//
// The first version scattered a 5-tone hue-shifted ramp with a coordinate hash.
// It measured well for evenness but read as noise: busy, then tiring. The fix
// was never fewer marks -- this pattern marks MORE cells than that one did
// (20% vs 19.5%) -- it was less contrast, in two steps. Spread against the base
// went 70 -> 13, which still showed dots at 1:1, then 13 -> 5, which does not.
// A repeating pattern gets filed as texture and ignored; random dots keep
// looking like information. Terrain is the floor an actor stands on: it loses.
//
// Judge terrain at 1:1 (one cell = ART_PX screen pixels, tiles 64px). The
// 3-4x renders used earlier exaggerated the noise and sent two rounds of this
// in the wrong direction.
//
// The lattice is laid out in 4px steps, as it was on the 16-cell tile, and its
// period must be coprime with that tile's 16 (5 for grass, 6 for path) or the
// marks line up with the tile edge and the 64px grid reappears. Each mark is a
// blade a cell wide and four tall, its top leaning a cell on alternate rows
// (four cells, the 2x2 block it was): 2px marks spaced as before keep the
// texture's grain, where a 2px dot at every lattice point would have made it
// twice as fine and busier. Variations are phase shifts of the one pattern,
// offset by `seed`. Not seed*3: at period 6 that collapses to phases 0,3,0,3
// and two of the four variants come out byte-identical, silently costing half
// the variation.
