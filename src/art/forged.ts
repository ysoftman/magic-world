// The forged gear's overlays and their battle copies, once per game (see
// ui/Blacksmith.ts bakeCraftedGear). Baking an existing key again would
// draw over it.
export function bakeForgedGear(this: Phaser.Scene): void {
  if (!this.textures.exists("equip-drake-blade")) makeTexture(this, "equip-drake-blade", DRAKE_BLADE_32, DRAKE_BLADE_PALETTE, ART_PX);
  if (!this.textures.exists("equip-glacier-mail")) makeTexture(this, "equip-glacier-mail", GLACIER_MAIL_32, GLACIER_MAIL_PALETTE, ART_PX);
  if (!this.textures.exists("equip-drake-blade@hd")) makeTexture(this, "equip-drake-blade@hd", DRAKE_BLADE_64, DRAKE_BLADE_PALETTE, 1);
  if (!this.textures.exists("equip-glacier-mail@hd")) makeTexture(this, "equip-glacier-mail@hd", GLACIER_MAIL_64, GLACIER_MAIL_PALETTE, 1);
}
