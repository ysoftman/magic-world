// The monsters as the battle draws them (battleHd.ts), all but the bosses and
// the giant (art/hdBosses.ts): grids of 64 cells drawn a texel a cell
// (makeTexture's px 1), so their textures are the 64px of the 32-cell art
// they stand for, and the battle's 2x makes a cell 2px on screen, the field's
// density, where the 32-cell art was 4px there. Each is baked under the art's
// key and "@hd" with the art's own palette, every variant its grid carries
// (the golden and magma slimes, the cursed goblin, the silver wasp, the
// aurora moth) too; no palette gained a key.
//
// Each is its 32-cell grid's layout doubled, a cell (x, y) there the cells
// (2x..2x+1, 2y..2y+1) here: the bounding box, the lowest row (the battle's
// footing reads the 32-cell art) and the centre are where they were, so the
// shadow, a flier's lift and the status sheets still fit. Drafted from the
// 32-cell grids through Scale2x with the eyes, mouths and glints kept as
// blocks (a full Scale2x bent them: almond eyes, a curved mouth), the outline
// then thinned to one cell (2px) in its own colour, and redrawn by hand with
// what 32 cells had no room for:
//
// - the slimes: round eyes with a glint up-left and a small one down-right,
//   the smile one cell, a reflected rim on the shadow side low right (g),
//   bubbles drifting in the jelly.
// - the goblins: pointed ears lit at the tip, angry brows one line down to
//   the nose, eyes cut by them, a nose with nostrils, a grin with lower fangs
//   rising off the lip over the mouth's dark (R), the arms' line against the
//   flank one cell, the chin's shadow on the neck, a chest line, a navel and
//   folds in the loincloth.
// - the wolf: brows one line, slanted eyes with the pupil toward the nose, a
//   black nose pad lit on top down the philtrum, a snarl with the fangs hanging
//   into the mouth over a tongue (p), the forehead's mask to a point between
//   the eyes, fur strands off the ruff's points and down the bib, a fur rim on
//   the ears and tufts at their base, toes.
// - the bat: the membranes plain, finger bones two cells from the wrist to
//   each scallop point, the leading edge lit (z, b on the shaded wing), the lit
//   wing's trailing edge a step darker, round eyes with a glint, an open
//   screech with the fangs hanging into it over a tongue (e).
// - the wasps: veins in the wings from the root out and a lit streak on the
//   far one, a sheen (j) across the top of each visor eye and on the lower
//   black band, fuzz on the thorax.
// - the spider: glossy eyes, a glint up-left and the red darkening to the
//   lower right, the small ones a glint each, fangs curling in at the tips, a
//   sheen (q) on the head and the abdomen.
// - the orc: strands in the topknot, the hairline one cell, heavy brows two
//   cells slanting to the nose, eyes with a glint, the mouth two cells between
//   tusks curving out, the jaw's outline one cell, the arms' line one cell,
//   bone studs on the bandolier, folds in the loincloth and grain in the club.
// - the wisp: the hollow eyes rounded, flame tongues licking up toward the
//   tip, the tail a tapering curl with its core lit (d) where it is wide
//   enough.
// - the moths: a frosted rim a step lighter along the wings' outer edges,
//   veins a step darker fanning from the body round the eyespots, a glint in
//   each eyespot, round eyes with a glint, the abdomen's segments lit on the
//   left.
// - the yeti: short strands of fur hanging in each band (a step darker,
//   lighter in the shadow), bangs over the face, round eyes with a glint, the
//   grumpy mouth one line with its corners down.
// - the imp: horns tapering to a point and ringed on the lit side, slanted
//   eyes hot at the outer end, the grin's corners curling up, the tail's flame
//   with an orange edge on its tongues and a white-hot core.
// - the salamander: the crest's flames white-hot only at the root and
//   pointed, a round eye with a reptile's slit and a shade under it, the jaw
//   under the mouth's line, a nostril, plates across the belly and a lit stripe
//   down the tail.

