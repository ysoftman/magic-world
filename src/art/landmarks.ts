// Their winter look ("<key>-winter"): snow under the outline on every column's
// top, two to four cells of it and the lowest in shade, the depth stepping
// every three columns so the edge is lumpy rather than ruled; roofs, the
// awning, the tent's cone and the palisade's points all catch it. Baked
// through `scene`, not `this`: check:art reads the plain grids, and this
// only recolours them.
const SNOW_CAP_PALETTE = { n: 0xf2f7fb, N: 0xc9d9e6 };
function snowCapped(rows: readonly string[]): string[] {
  const g = rows.map((r) => [...r]);
  for (let x = 0; x < g[0].length; x++) {
    const y0 = g.findIndex((r) => r[x] !== ".");
    if (y0 < 0) continue;
    const lump = Math.floor(x / 3);
    const depth = 2 + ((lump * 7 + (lump >> 1) * 3) % 3);
    for (let k = 1; k <= depth + 1; k++) {
      const row = g[y0 + k];
      if (!row || row[x] === "." || row[x] === "b") break;
      row[x] = k === depth + 1 ? "N" : "n";
    }
  }
  return g.map((r) => r.join(""));
}
const WORKPLACE_ART: ReadonlyArray<readonly [string, readonly string[], Record<string, number>]> = [
  ["hut-elder", ELDER_HUT_64, ELDER_HUT_PALETTE],
  ["stall-shop", SHOP_STALL_64, SHOP_STALL_PALETTE],
  ["forge", FORGE_64, FORGE_PALETTE],
  ["gate-arena", ARENA_GATE_64, ARENA_GATE_PALETTE],
  ["tent-gambler", GAMBLER_TENT_64, GAMBLER_TENT_PALETTE],
  ["lodge-hunter", HUNTER_LODGE_64, HUNTER_LODGE_PALETTE],
];
function makeWorkplaceSnow(scene: Phaser.Scene): void {
  for (const [key, rows, palette] of WORKPLACE_ART)
    makeTexture(scene, `${key}-winter`, snowCapped(rows), { ...palette, ...SNOW_CAP_PALETTE }, ART_PX);
}

